/// Tokens produced by the openCypher lexical scanner.
#[derive(Debug, Clone, PartialEq)]
pub enum Token {
    Match,
    Create,
    Set,
    Delete,
    Detach,
    Where,
    Return,
    Order,
    By,
    Limit,
    Skip,
    And,
    Or,
    Asc,
    Desc,
    Count,
    Sum,
    Avg,
    Min,
    Max,
    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Colon,
    Comma,
    Dot,
    Star,
    Eq,
    Neq,
    Lt,
    Lte,
    Gt,
    Gte,
    ArrowRight,
    ArrowLeft,
    Dash,
    Parameter(String),
    Ident(String),
    StringLit(String),
    IntLit(i64),
    FloatLit(f64),
}
